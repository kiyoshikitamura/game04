import assert from 'node:assert/strict';
import { projectRecordedBattleFrame as project } from '../../src/domain/presentation/recordedBattlePresentation.ts';
const skill = {id:'slash',name:'斬撃',effects:[{type:'damage',power:100}]};
const unit = (id,hp,skills=[]) => ({id,hp,maxHp:100,sp:0,maxSp:60,count:2,actions:0,statuses:[],phase:null,skills});
const frame = (index,event,hp,extra={}) => ({index,event,kind:'action',wave:1,actorId:'ally',skillId:'slash',party:[unit('ally',100,[skill])],enemies:[unit('enemy',hp)],partySp:40,maxSp:400,burst:false,...extra});
const frames = [frame(0,'action_start',100),frame(1,'damage',70,{targetIds:['enemy'],hits:[10,10,10]}),frame(2,'effect_applied',70,{targetIds:['enemy']}),frame(3,'heal',90,{targetIds:['enemy']}),frame(4,'burst_start',90),frame(5,'action_start',90),frame(6,'damage',60,{targetIds:['enemy'],hits:[30]}),frame(7,'effect_miss',60,{targetIds:['enemy']}),frame(8,'wave',100,{wave:2,skillId:undefined,actorId:undefined}),frame(9,'end',100,{wave:2,kind:'end'})];
const result = {party:[{id:'ally',skills:[skill]}],waves:[[{id:'enemy'}],[{id:'enemy'}]],frames};
const original=JSON.stringify(result);
assert.equal(project(result,0).cutIn,'skill');
assert.equal(project(result,1).cutIn,null);
assert.deepEqual(project(result,1).impacts,[{targetId:'enemy',amount:30,type:'damage',hits:[10,10,10]}]);
assert.equal(project(result,3).impacts[0].amount,20);
assert.equal(project(result,3).impacts[0].type,'heal');
assert.equal(project(result,4).cutIn,'burst');
assert.equal(project(result,6).cutIn,null);
assert.equal(project(result,7).impacts[0].type,'status','Failed status application is not a missed attack');
assert.deepEqual(project(result,8).impacts,[],'Wave replacement cannot create false healing');
assert.equal(project(result,8).activeActorId,undefined);
assert.equal(project(result,9).cutIn,null);
assert.equal(JSON.stringify(result),original,'Presentation must not mutate saved battle snapshots');
frames[0].skillId='basic';
assert.equal(project(result,0).isSkill,false);
assert.equal(project(result,0).cutIn,null);
console.log('PASS: recorded HP/multi-hit/heal, cut-in lifecycle, status failure, wave reset and snapshot immutability');

frames[1].enemies[0].hp=0; frames[1].hits=[100,100,100];
assert.equal(project(result,1).impacts[0].amount,300,'Recorded overkill damage must not be truncated to remaining HP');
frames[1].event='dot'; frames[1].hits=undefined; frames[1].text='敵 継続ダメージ −350';
assert.equal(project(result,1).impacts[0].amount,350,'Recorded DOT overkill must not be truncated');
console.log('PASS: direct and DOT overkill retain authoritative recorded damage');
